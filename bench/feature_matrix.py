"""Run the whole feature matrix and write docs/feature-matrix.md.

    python bench/feature_matrix.py
"""

from __future__ import annotations

import asyncio
import platform
import subprocess
import sys
import tempfile
import time
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "tests"))

from matrix import make_project, run_all, run_mcp  # noqa: E402

from keelyard import __version__, selftest  # noqa: E402


def main() -> int:
    t0 = time.time()
    with tempfile.TemporaryDirectory() as t:
        cli = run_all(Path(t))
    with tempfile.TemporaryDirectory() as t:
        proj, env = make_project(Path(t))
        for _ in range(2):
            subprocess.run([sys.executable, "-m", "keelyard.cli", "rewind", "snap"], cwd=proj, env=env, check=True, capture_output=True)
            (proj / "app.py").write_text((proj / "app.py").read_text() + "# change\n")
        mcp = asyncio.run(run_mcp(proj, env))
    st = selftest.run()
    total = len(cli) + len(mcp) + len(st.checks)
    passed = sum(o.ok for o in cli) + sum(m[2] for m in mcp) + sum(c.ok for c in st.checks)
    git = subprocess.run(["git", "rev-parse", "--short", "HEAD"], cwd=ROOT, capture_output=True, text=True).stdout.strip()
    md = ["# Feature matrix", "",
          "Every CLI command and flag, every hook event per agent, every MCP tool, and the end-to-end agent self-test, "
          "run against throwaway projects. Generated by `python bench/feature_matrix.py`.", "",
          f"**{passed} / {total} passed** · keelyard {__version__} · commit `{git}` · Python {platform.python_version()} · "
          f"{platform.system()} · {time.strftime('%Y-%m-%d')} · {time.time() - t0:.0f}s", "",
          "Expected exit codes: `0` ok, `1` error, `2` usage error, `3` check not passed. "
          "Rows that test an error path pass when keelyard fails *cleanly* with the right code.", ""]
    area = None
    for o in cli:
        if o.case.area != area:
            area = o.case.area
            md += ["", f"## {area}", "", "| | case | command | exit | ms |", "|---|---|---|---|---|"]
        argv = [a.replace(sys.executable, "python") for a in o.case.argv]
        cmd = "keelyard " + " ".join(a if len(a) < 40 else a[:37] + "..." for a in argv)
        md.append(f"| {'✓' if o.ok else '✗'} | {o.case.name}{' — ' + o.note if o.note else ''} | `{cmd}` | {o.exit} | {o.ms} |")
    md += ["", "## MCP tools", "", "Called over stdio by the official MCP client. Error rows check that bad input is refused.", "",
           "| | tool | arguments | result |", "|---|---|---|---|"]
    for tool, args, ok, note in mcp:
        a = str(args).replace(sys.executable, "python")
        md.append(f"| {'✓' if ok else '✗'} | `{tool}` | `{a if len(a) < 60 else a[:57] + '...'}` | {note or 'ok'} |")
    md += ["", "## Agent self-test", "", "`keelyard selftest`: a scripted agent completes a task through MCP and Claude Code hook payloads.", "",
           "| | step | detail | ms |", "|---|---|---|---|"]
    for c in st.checks:
        md.append(f"| {'✓' if c.ok else '✗'} | {c.name} | {c.detail.replace('|', '/')} | {c.ms:.0f} |")
    (ROOT / "docs" / "feature-matrix.md").write_text("\n".join(md) + "\n")
    print(f"{passed}/{total} passed -> docs/feature-matrix.md")
    return 0 if passed == total else 1


if __name__ == "__main__":
    raise SystemExit(main())
