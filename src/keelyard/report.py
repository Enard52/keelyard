"""Self-contained HTML proof report (no external assets, safe to attach to a PR)."""

from __future__ import annotations

import base64
import datetime as dt
import html
from pathlib import Path

from .proof import Proof
from .snapshot import Shadow

CSS = """
body{font:15px/1.5 -apple-system,Segoe UI,Inter,sans-serif;margin:0;background:#f6f5f2;color:#1d1d1b}
main{max-width:920px;margin:40px auto;padding:0 24px}
h1{font-size:22px;margin:0 0 4px} h2{font-size:15px;text-transform:uppercase;letter-spacing:.06em;color:#6b6a65;margin:32px 0 10px}
.verdict{display:inline-block;padding:4px 10px;border-radius:6px;font-weight:600;font-size:13px}
.ok{background:#dff3e4;color:#14532d}.bad{background:#fde2e1;color:#7f1d1d}
.card{background:#fff;border:1px solid #e4e2dc;border-radius:10px;padding:14px 16px;margin:8px 0}
pre{background:#1d1d1b;color:#ecebe6;padding:12px;border-radius:8px;overflow:auto;font-size:12px;max-height:280px}
.muted{color:#6b6a65;font-size:13px} img{max-width:100%;border:1px solid #e4e2dc;border-radius:8px}
table{border-collapse:collapse;width:100%} td{padding:6px 8px;border-top:1px solid #eeece6;vertical-align:top;font-size:13px}
"""


def _t(ts: float) -> str:
    return dt.datetime.fromtimestamp(ts).strftime("%Y-%m-%d %H:%M:%S")


def render(proof: Proof) -> Path:
    b = proof.load()
    gaps = proof.missing()
    e = html.escape
    parts = [f"<!doctype html><meta charset=utf-8><title>Proof: {e(b.session)}</title><style>{CSS}</style><main>"]
    verdict = '<span class="verdict ok">PROVEN</span>' if not gaps else f'<span class="verdict bad">{len(gaps)} GAP(S)</span>'
    parts.append(f"<h1>Proof of work</h1><p class=muted>session {e(b.session)} · started {_t(b.started)}</p>{verdict}")
    if b.task:
        parts.append(f"<h2>Task</h2><div class=card>{e(b.task)}</div>")
    if gaps:
        parts.append("<h2>Missing</h2>" + "".join(f"<div class=card>{e(g)}</div>" for g in gaps))
    parts.append("<h2>Requirements</h2><table>")
    for r in b.requirements:
        mark = "&#10003;" if r["done"] else "&#9675;"
        parts.append(f"<tr><td>{mark}</td><td><b>{e(r['text'])}</b><br><span class=muted>{e(r.get('evidence', ''))}</span></td></tr>")
    parts.append("</table>")
    parts.append("<h2>Test runs</h2>")
    for t in b.test_runs:
        cls = "ok" if t["exit"] == 0 else "bad"
        parts.append(
            f"<div class=card><span class='verdict {cls}'>{e(t['phase'])} · exit {t['exit']}</span> "
            f"<code>{e(t['cmd'])}</code> <span class=muted>{_t(t['ts'])} · {t['seconds']}s</span><pre>{e(t['tail'])}</pre></div>"
        )
    if b.screenshots:
        parts.append("<h2>Screenshots</h2>")
        for s in b.screenshots:
            p = Path(s["path"])
            if p.exists():
                data = base64.b64encode(p.read_bytes()).decode()
                parts.append(f"<div class=card><p class=muted>{e(s['url'])} · {_t(s['ts'])}</p><img src='data:image/png;base64,{data}'></div>")
    steps = [s for s in Shadow(proof.cfg).steps() if s.ts >= b.started]
    if steps:
        parts.append("<h2>Timeline</h2><table>")
        for s in steps:
            files = ", ".join(s.files[:8]) + (f" +{len(s.files) - 8}" if len(s.files) > 8 else "")
            parts.append(f"<tr><td>#{s.step}</td><td>{e(s.tool)}</td><td class=muted>{_t(s.ts)}</td><td>{e(files)}</td></tr>")
        parts.append("</table>")
    parts.append("<p class=muted>Generated by keelyard. Evidence is what the agent ran on this machine; review before trusting.</p></main>")
    out = proof.dir / "report.html"
    out.write_text("".join(parts))
    return out
